const fs = require("node:fs");
const path = require("node:path");

const [recipeDirectory] = process.argv.slice(2);
if (!recipeDirectory) {
    throw new Error("Usage: node scripts/Generate-CraftedIndex.cjs <CraftingPath/Data>");
}

const root = path.join(__dirname, "..");
const gear = fs.readFileSync(path.join(root, "GearIndex.lua"), "utf8");
const slots = new Map(Array.from(gear.matchAll(/^\s*\[(\d+)\] = \{ (\d+),/gm),
    match => [Number(match[1]), Number(match[2])]));
const excluded = new Set([18, 24, 27]); // Bags, ammunition, and quivers.
const professions = [
    "Alchemy", "Blacksmithing", "Cooking", "Enchanting",
    "Engineering", "FirstAid", "Leatherworking", "Tailoring",
];

const crafted = new Set();
for (const profession of professions) {
    const data = fs.readFileSync(path.join(recipeDirectory, profession + ".lua"), "utf8");
    for (const match of data.matchAll(/^\s*\[\d+\]\s*=\s*\{[^\r\n]*?\bout\s*=\s*\{\s*(\d+)\s*,/gm)) {
        const id = Number(match[1]);
        const slot = slots.get(id);
        if (slot && !excluded.has(slot)) crafted.add(id);
    }
}
if (crafted.size < 200) throw new Error("Crafted gear index is unexpectedly small.");

const index = [...crafted].sort((a, b) => a - b);
const lines = [];
for (let i = 0; i < index.length; i += 8) {
    lines.push("    " + index.slice(i, i + 8).map(id => `[${id}] = true,`).join(" "));
}
const output = path.join(root, "CraftedIndex.lua");
fs.writeFileSync(output, [
    "-- Generated by scripts/Generate-CraftedIndex.cjs from Forever recipe output IDs in CraftingPath.",
    "local _, addon = ...",
    "addon.crafted = {",
    ...lines,
    "}",
    "",
].join("\n"));
console.log(`Wrote ${crafted.size} crafted equipment IDs to ${output}.`);

const fs = require("node:fs");
const path = require("node:path");

const [itemSparsePath, cachePath] = process.argv.slice(2);
if (!itemSparsePath || !cachePath) {
    throw new Error("Usage: node scripts/Generate-GearIndex.cjs <ItemSparse.db2> <DBCache.bin>");
}

const base = fs.readFileSync(itemSparsePath);
const cache = fs.readFileSync(cachePath);
const BUILD = 70938;
const ITEM_SPARSE_HASH = 0x919be54e;
// ItemSparse layout 6FCC3191 in WoWDBDefs. Offsets are relative to the end
// of the five inline localized strings in both sparse records and hotfixes.
const STAT_TYPES = 116;
const BONDING = 293;
const REQUIRED_LEVEL = 298;
const INVENTORY_TYPE = 299;
const QUALITY = 300;
const RECORD_BYTES = 302;
const SECTION = 204;
// Bit positions shared with GearSearch.lua. Multiple client IDs can represent
// the same searchable stat, such as a generic or school-specific hit rating.
const statBits = {
    3: 1, 4: 2, 5: 4, 6: 8, 7: 16,
    45: 32, 41: 64, 42: 128,
    16: 256, 17: 256, 18: 256, 31: 256,
    19: 512, 20: 512, 21: 512, 32: 512,
    28: 1024, 29: 1024, 30: 1024, 36: 1024,
    37: 2048, 12: 4096, 13: 8192, 14: 16384, 15: 32768,
    48: 65536, 38: 131072, 39: 262144, 43: 524288,
    47: 1048576, 44: 2097152, 35: 4194304, 50: 8388608,
    46: 16777216, 51: 33554432, 52: 67108864, 54: 134217728,
    55: 268435456, 56: 536870912, 53: 1073741824,
    71: 7, 72: 3, 73: 5, 74: 6,
};

if (base.toString("ascii", 0, 4) !== "WDC5" ||
    base.readUInt32LE(152) !== ITEM_SPARSE_HASH ||
    base.readUInt32LE(156) !== 0x6fcc3191) {
    throw new Error("Expected the Forever 70938 ItemSparse layout.");
}
if (cache.toString("ascii", 0, 4) !== "XFTH" ||
    cache.readUInt32LE(4) !== 9 || cache.readUInt32LE(8) !== BUILD) {
    throw new Error("Expected the Forever 70938 hotfix cache.");
}

const gear = new Map();
function readGear(buffer, id, start, end) {
    let fields = start;
    for (let i = 0; i < 5; i++) {
        const terminator = buffer.indexOf(0, fields);
        if (terminator < 0 || terminator >= end) throw new Error(`Invalid item strings for ${id}`);
        fields = terminator + 1;
    }
    if (end - fields < RECORD_BYTES) throw new Error(`Truncated item record for ${id}`);

    const slot = buffer.readInt8(fields + INVENTORY_TYPE);
    if (slot <= 0 || slot > 28) {
        gear.delete(id);
        return;
    }
    const requiredLevel = buffer.readInt8(fields + REQUIRED_LEVEL);
    let stats = 0;
    for (let i = 0; i < 10; i++) {
        const stat = buffer.readInt32LE(fields + STAT_TYPES + i * 4);
        stats |= statBits[stat] || 0;
    }
    const quality = buffer.readUInt8(fields + QUALITY);
    const bonding = buffer.readUInt8(fields + BONDING);
    gear.set(id, [slot, requiredLevel, stats, quality, bonding]);
}

const count = base.readUInt32LE(SECTION + 32);
const copyCount = base.readUInt32LE(SECTION + 36);
const copies = base.readUInt32LE(SECTION + 20) + base.readUInt32LE(SECTION + 24);
const offsets = copies + copyCount * 8;
const ids = offsets + count * 6;
for (let i = 0; i < count; i++) {
    const offset = offsets + i * 6;
    const start = base.readUInt32LE(offset);
    const end = start + base.readUInt16LE(offset + 4);
    readGear(base, base.readUInt32LE(ids + i * 4), start, end);
}
for (let i = 0; i < copyCount; i++) {
    const offset = copies + i * 8;
    const original = gear.get(base.readUInt32LE(offset + 4));
    if (original) gear.set(base.readUInt32LE(offset), original);
}

console.log(`Read ${gear.size} equipment entries from ItemSparse.`);
for (let offset = 44; offset < cache.length;) {
    const start = offset + 32;
    const end = start + cache.readUInt32LE(offset + 24);
    if (end > cache.length || cache.toString("ascii", offset, offset + 4) !== "XFTH") {
        throw new Error("Invalid hotfix record.");
    }
    if (cache.readUInt32LE(offset + 16) === ITEM_SPARSE_HASH) {
        const id = cache.readUInt32LE(offset + 20);
        const state = cache.readUInt32LE(offset + 28);
        if (state === 1) readGear(cache, id, start, end);
        if (state === 2) gear.delete(id);
    }
    offset = end;
}

const root = path.join(__dirname, "..");
const names = fs.readFileSync(path.join(root, "ItemIndex.lua"), "utf8");
const knownIDs = new Set(Array.from(names.matchAll(/^\s*\[(\d+)\] = "/gm), match => Number(match[1])));
const lines = [...gear].filter(([id]) => knownIDs.has(id)).sort(([left], [right]) => left - right)
    .map(([id, fields]) => `    [${id}] = { ${fields.join(", ")} },`);
if (lines.length < 5000) throw new Error("Equipment index is unexpectedly small.");

const output = path.join(root, "GearIndex.lua");
fs.writeFileSync(output, [
    "-- Generated by scripts/Generate-GearIndex.cjs from Forever 70938 client data and hotfixes.",
    "-- Fields are inventory type, required character level, stat flags, quality, and bonding.",
    "local _, addon = ...",
    "addon.gear = {",
    ...lines,
    "}",
    "",
].join("\n"));
console.log(`Wrote ${lines.length} searchable equipment entries to ${output}.`);
